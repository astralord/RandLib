#!/usr/bin/env python3
"""Generates include/randlib/core/ziggurat_tables.hpp.

The ziggurat tables of the normal and exponential samplers (256 layers, Marsaglia and Tsang 2000)
used to be computed at static initialization with std::log and std::sqrt, which no compiler can
evaluate at compile time. This script evaluates the same recurrences in 40-digit arithmetic and
writes them as literal constexpr arrays.

Usage: tools/gen_tables.py > include/randlib/core/ziggurat_tables.hpp
"""

import mpmath as mp

mp.mp.dps = 40
SIZE = 257


def table(area, x0, f0, x1, f1, inverse):
    """Layers (f(x_i), x_i): x_i = f^-1(f(x_(i-1))) and f(x_i) = f(x_(i-1)) + area / x_i."""
    rows = [(f0, x0), (f1, x1)]
    for _ in range(2, SIZE - 1):
        x = inverse(rows[-1][0])
        rows.append((rows[-1][0] + area / x, x))
    rows.append((mp.mpf(0), mp.mpf(0)))
    rows[-1] = (rows[-1][0], mp.mpf(0))
    return rows


def literal(v):
    return mp.nstr(v, 21, min_fixed=-5, max_fixed=5, strip_zeros=False) + "L"


def emit(name, rows, comment):
    print(f"/// {comment}")
    print(f"inline constexpr std::array<std::pair<long double, long double>, {SIZE}> {name} = {{{{")
    for f, x in rows:
        print(f"    {{{literal(f)}, {literal(x)}}},")
    print("}};")


normal = table(mp.mpf("4.92867323399e-3"), mp.mpf("3.9107579595370918075"), mp.mpf("0.001260285930498597"),
               mp.mpf("3.6541528853610088"), mp.mpf("0.002609072746106362"), lambda f: mp.sqrt(-2 * mp.log(f)))
exponential = table(mp.mpf("3.9496598225815571993e-3"), mp.mpf("8.697117470131049720307"), mp.mpf("0.00045413435384149675"),
                    mp.mpf("7.69711747013104972"), mp.mpf("0.0009672692823271745203"), lambda f: -mp.log(f))

print("#pragma once")
print()
print("// Generated by tools/gen_tables.py; do not edit.")
print()
print("#include <array>")
print("#include <utility>")
print()
print("namespace randlib::detail")
print("{")
print()
emit("normalZiggurat", normal, "(exp(-x^2 / 2), x) at the layer boundaries of the normal ziggurat")
print()
emit("exponentialZiggurat", exponential, "(exp(-x), x) at the layer boundaries of the exponential ziggurat")
print()
print("} // namespace randlib::detail")
