/**
 * @brief The GammaDistribution class <BR>
 * Abstract class for Gamma distribution
 *
 * f(x | α, β) = β^α / Γ(α) * x^(α-1) * exp(-βx),
 * where Γ(α) denotes Gamma function
 *
 * Notation X ~ Γ(α, β)
 *
 * Related distributions: <BR>
 * σX ~ Γ(α, σβ) <BR>
 * If X ~ Γ(1, β), then X ~ Exp(β) <BR>
 * If X ~ Γ(0.5 * n, 0.5), then X ~ χ^2(n) <BR>
 * If X ~ Γ(k, β) for integer k, then X ~ Erlang(k, β)
 */
template <typename RealType>
class GammaDistribution : virtual public ContinuousDistribution<RealType>
{
    RealType variate(detail::EngineRef g) const override { return (*this)(g); }
    void sample(detail::EngineRef g, std::span<RealType> outputData) const override;

protected:
    double alpha = 1; ///< shape α
    double beta = 1; ///< rate β
    double theta = 1; ///< scale θ = 1/β
    double lgammaAlpha = 0; ///< log(Γ(α))
    double pdfCoef = 0; ///< α * log(β) - log(Γ(α))
    double logAlpha = 0; ///< log(α)
    double logBeta = 0; ///< log(β)
    double digammaAlpha = -randlib::consts::egamma; ///< ψ(α)

private:
    /// constants for faster sampling
    struct genCoef_t
    {
        double t, b;
    } genCoef = {0, 0};

protected:
    GammaDistribution(double shape, double rate);

public:
    virtual ~GammaDistribution() {}

    [[nodiscard]] Support SupportType() const override { return Support::RightSemiFinite; }
    [[nodiscard]] RealType MinValue() const override { return 0; }
    [[nodiscard]] RealType MaxValue() const override { return INFINITY; }

protected:
    /**
     * @param shape α
     * @param rate β
     */
    void SetParameters(double shape, double rate);
    /**
     * @brief SetShape
     * @param shape α
     */
    void SetShape(double shape);

public:
    /**
     * @return α
     */
    [[nodiscard]] inline double GetShape() const noexcept { return alpha; }
    /**
     * @return θ = 1/β
     */
    [[nodiscard]] inline double GetScale() const noexcept { return theta; }
    /**
     * @return β
     */
    [[nodiscard]] inline double GetRate() const noexcept { return beta; }
    /**
     * @return log(Γ(α))
     */
    [[nodiscard]] inline double GetLogGammaShape() const noexcept { return lgammaAlpha; }
    /**
     * @return log(α)
     */
    [[nodiscard]] inline double GetLogShape() const noexcept { return logAlpha; }
    /**
     * @return ψ(α)
     */
    [[nodiscard]] inline double GetDigammaShape() const noexcept { return digammaAlpha; }
    /**
     * @return log(β)
     */
    [[nodiscard]] inline double GetLogRate() const noexcept { return logBeta; }

    [[nodiscard]] double f(const RealType &x) const override;
    [[nodiscard]] double logf(const RealType &x) const override;
    [[nodiscard]] double F(const RealType &x) const override;
    double logF(const RealType &x) const;
    [[nodiscard]] double S(const RealType &x) const override;
    double logS(const RealType &x) const;

private:
    enum GENERATOR_ID
    {
        INTEGER_SHAPE, ///< Erlang distribution for α = 1, 2, 3
        ONE_AND_A_HALF_SHAPE, ///< α = 1.5
        SMALL_SHAPE, ///< α < 0.34
        FISHMAN, ///< 1 < α < 1.2
        MARSAGLIA_TSANG ///< 0.34 < α < 1 or α >= 1.2
    };

    /**
     * @param shape α
     * @return id of used variate generator according to the shape
     */
    static GENERATOR_ID getIdOfUsedGenerator(double shape)
    {
        if (shape < 0.34)
            return SMALL_SHAPE;
        if (shape <= 3.0 && math::detail::areClose(shape, std::round(shape)))
            return INTEGER_SHAPE;
        if (math::detail::areClose(shape, 1.5))
            return ONE_AND_A_HALF_SHAPE;
        if (shape > 1.0 && shape < 1.2)
            return FISHMAN;
        return MARSAGLIA_TSANG;
    }

    /**
     * @param shape α
     * @return gamma variate, generated by sum of exponentially distributed random variables
     */
    template <std::uniform_random_bit_generator G>
    static RealType variateThroughExponentialSum(int shape, G &g);
    /**
     * @return gamma variate for α = 1.5
     */
    template <std::uniform_random_bit_generator G>
    static RealType variateForShapeOneAndAHalf(G &g);
    /**
     * @return gamma variate for small α, using Best algorithm
     */
    template <std::uniform_random_bit_generator G>
    RealType variateBest(G &g) const;
    /**
     * @param shape α
     * @return gamma variate for small α, using Ahrens-Dieter algorithm (if we have no pre-calculated values)
     */
    template <std::uniform_random_bit_generator G>
    static RealType variateAhrensDieter(double shape, G &g);
    /**
     * @param shape α
     * @return gamma variate, using Fishman algorithm
     */
    template <std::uniform_random_bit_generator G>
    static RealType variateFishman(double shape, G &g);
    /**
     * @param shape α
     * @return gamma variate, using Marsaglia-Tsang algorithm
     */
    template <std::uniform_random_bit_generator G>
    static RealType variateMarsagliaTsang(double shape, G &g);

public:
    /**
     * @param shape α
     * @param g uniform random bit generator
     * @return gamma variate with shape α and unity rate
     */
    template <std::uniform_random_bit_generator G>
    [[nodiscard]] static RealType StandardVariate(double shape, G &g);
    /**
     * @param shape α
     * @param rate β
     * @param g uniform random bit generator
     * @return gamma variate with shape α and rate β
     */
    template <std::uniform_random_bit_generator G>
    [[nodiscard]] static RealType Variate(double shape, double rate, G &g);

    template <std::uniform_random_bit_generator G>
    [[nodiscard]] RealType operator()(G &g) const;

    /**
     * @return E[X]
     */
    [[nodiscard]] long double Mean() const override;
    /**
     * @return E[ln(X)]
     */
    long double GeometricMean() const;
    /**
     * @return Var(X)
     */
    [[nodiscard]] long double Variance() const override;
    /**
     * @return Var(ln(X))
     */
    long double GeometricVariance() const;
    [[nodiscard]] RealType Mode() const override;
    [[nodiscard]] RealType Median() const override;
    [[nodiscard]] long double Skewness() const override;
    [[nodiscard]] long double ExcessKurtosis() const override;

private:
    /// quantile auxiliary functions
    RealType initRootForSmallP(double r) const;
    RealType initRootForLargeP(double logQ) const;
    RealType initRootForLargeShape(double p) const;
    RealType initRootForLargeShape1m(double p) const;
    RealType quantileInitialGuess(double p) const;
    RealType quantileInitialGuess1m(double p) const;

    /**
     * derivative of probability density function
     * @param x
     * @return f'(x)
     */
    double df(RealType x) const;
    /**
     * derivative of pdf, divided by pdf
     * @param x
     * @return f'(x) / f(x)
     */
    double dfDivf(RealType x) const;
    RealType quantileImpl(double p, RealType initValue) const override;
    RealType quantileImpl(double p) const override;
    RealType quantileImpl1m(double p, RealType initValue) const override;
    RealType quantileImpl1m(double p) const override;

    std::complex<double> CFImpl(double t) const override;
};

