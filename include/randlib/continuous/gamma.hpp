/**
 * @brief The ErlangRand class <BR>
 * Erlang distibution
 *
 * Notation: X ~ Erlang(k, β)
 *
 * Related distributions: <BR>
 * X ~ Y_1 + Y_2 + ... + Y_k, where Y_i ~ Exp(β) <BR>
 * X ~ Γ(k, β)
 */
template <typename RealType>
class ErlangRand final : public FreeRateGammaDistribution<RealType>
{
public:
    ErlangRand(int shape = 1, double rate = 1) : FreeRateGammaDistribution<RealType>(shape, rate) {}

    /// @return Erlang(k, β) with rate β
    [[nodiscard]] static ErlangRand FromShapeRate(int shape, double rate) { return ErlangRand(shape, rate); }

    /// @return Erlang(k, 1/θ) with scale θ
    [[nodiscard]] static ErlangRand FromShapeScale(int shape, double scale)
    {
        if (!(scale > 0.0))
            throw std::invalid_argument("Erlang distribution: scale should be positive");
        return ErlangRand(shape, 1.0 / scale);
    }
    [[nodiscard]] std::string Name() const override;
    void SetParameters(size_t shape, double rate);
    void SetShape(size_t shape);
};

